# ---- Section 1  (STEP 1): your first program ---------------
# print() puts words on the screen. Think of it as the till
# printing a line of receipt paper. This is your ribbon-cutting.
print("Hello World")

# Now let's say it the way our shop would say it.
print("Welcome to The Cozy Bean!")


# ---- Section 2  (STEP 2): the till is a calculator ---------
# Python does maths before it knows anything else about your shop.
# Three lattes at $3.50 each:
print(3 * 3.50)

# Those three lattes plus one muffin at $2.25:
print(3 * 3.50 + 2.25)

# 📌 You saw this in class: our bean supplier drives 403 miles
# from London to Edinburgh. How far is that in kilometres?
print(403 * 1.60934)
